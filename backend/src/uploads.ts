import { randomUUID } from 'crypto';
import fs from 'fs';
import path from 'path';
import type { NextFunction, Request, Response } from 'express';
import multer from 'multer';
import { config } from './config';
import { HttpError } from './http';

const MIME_EXT: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
};

const CONTENT_TYPE: Record<string, string> = {
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
};

export const uploadReceipt = multer({
  storage: multer.diskStorage({
    destination: (_req, _file, callback) => {
      callback(null, config.uploadsDir);
    },
    filename: (_req, file, callback) => {
      const ext = MIME_EXT[file.mimetype] ?? '.bin';
      callback(null, `${randomUUID()}${ext}`);
    },
  }),
  limits: { fileSize: 5 * 1024 * 1024, files: 1 },
  fileFilter: (_req, file, callback) => {
    if (!MIME_EXT[file.mimetype]) {
      callback(new Error('Receipt must be a JPEG, PNG, or WebP image'));
      return;
    }
    callback(null, true);
  },
});

/** JSON creates a loan with no photo. Multipart may include one `receipt` file. */
export function acceptLoanBody(req: Request, res: Response, next: NextFunction) {
  const contentType = req.headers['content-type'] ?? '';
  if (!contentType.includes('multipart/form-data')) {
    next();
    return;
  }
  uploadReceipt.single('receipt')(req, res, (err: unknown) => {
    if (!err) {
      next();
      return;
    }
    if (err instanceof multer.MulterError && err.code === 'LIMIT_FILE_SIZE') {
      next(new HttpError(400, 'Receipt must be 5 MB or smaller'));
      return;
    }
    if (err instanceof Error) {
      next(new HttpError(400, err.message));
      return;
    }
    next(new HttpError(400, 'Could not upload receipt'));
  });
}

export async function discardUpload(filename: string | undefined): Promise<void> {
  if (!filename) return;
  await fs.promises.unlink(path.join(config.uploadsDir, filename)).catch(() => undefined);
}

export function resolveReceipt(filename: string): { absolutePath: string; contentType: string } {
  // Names are generated by us. Reject anything that could escape the uploads directory.
  if (!/^[0-9a-f-]{36}\.(jpg|png|webp)$/.test(filename)) {
    throw new HttpError(404, 'Receipt file is missing');
  }
  const root = path.resolve(config.uploadsDir);
  const absolutePath = path.resolve(root, filename);
  if (!absolutePath.startsWith(`${root}${path.sep}`)) {
    throw new HttpError(404, 'Receipt file is missing');
  }
  if (!fs.existsSync(absolutePath)) {
    throw new HttpError(404, 'Receipt file is missing');
  }
  const contentType = CONTENT_TYPE[path.extname(absolutePath)] ?? 'application/octet-stream';
  return { absolutePath, contentType };
}
