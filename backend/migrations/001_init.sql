-- MiniLedger schema.
-- Applied in filename order by `npm run migrate`, which records each file in schema_migrations.
--
-- users           one row per phone, created the first time an OTP is verified
-- otp_challenges  HMAC of a one-time code. The raw code is only printed to the server log.
-- loans           money the signed-in user lent to a friend
--
-- "Overdue" is not a column. A loan is overdue when it is still open and its due date
-- is before today's calendar date in Asia/Kolkata. Queries compute that themselves,
-- so the result does not depend on the database server's timezone setting.

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  phone text NOT NULL UNIQUE CHECK (phone ~ '^\+91[6-9][0-9]{9}$'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE otp_challenges (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  phone text NOT NULL CHECK (phone ~ '^\+91[6-9][0-9]{9}$'),
  code_hash text NOT NULL,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX otp_challenges_phone_created_at_idx
  ON otp_challenges (phone, created_at DESC);

CREATE TABLE loans (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  friend_name text NOT NULL CHECK (char_length(btrim(friend_name)) BETWEEN 1 AND 80),
  -- Rupees, not a float. numeric keeps the two decimal places exact.
  amount numeric(12, 2) NOT NULL CHECK (amount > 0 AND amount <= 10000000),
  due_date date NOT NULL CHECK (due_date BETWEEN DATE '2000-01-01' AND DATE '2100-12-31'),
  repaid_at timestamptz,
  -- Basename generated by the API. The image itself lives on disk under uploads/.
  receipt_filename text CHECK (
    receipt_filename IS NULL
    OR receipt_filename ~ '^[0-9a-f-]{36}\.(jpg|png|webp)$'
  ),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX loans_user_due_date_idx ON loans (user_id, due_date);
